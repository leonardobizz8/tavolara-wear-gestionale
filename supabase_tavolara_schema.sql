-- RPC protetta per consultare l'ordine dal token privato
CREATE OR REPLACE FUNCTION get_order_by_token(p_token TEXT)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    res json;
BEGIN
    SELECT json_build_object(
        'order', row_to_json(o),
        'items', (SELECT json_agg(row_to_json(i)) FROM order_items i WHERE i.order_id = o.id)
    )
    INTO res
    FROM orders o
    WHERE o.order_token = p_token;
    
    RETURN res;
END;
$$;

