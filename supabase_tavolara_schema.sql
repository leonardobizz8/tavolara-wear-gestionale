-- 1. Tabella Profili Utenti (Soci / Amministratori)
CREATE TABLE IF NOT EXISTS public.profiles (
    id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
    email TEXT NOT NULL,
    full_name TEXT,
    role TEXT NOT NULL DEFAULT 'partner' CHECK (role IN ('admin', 'partner', 'staff')),
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabella Clienti (Customers)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT NOT NULL,
    phone TEXT NOT NULL,
    delivery_address TEXT,
    delivery_zip TEXT,
    delivery_city TEXT,
    delivery_province TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_customers_email ON public.customers(email);

-- 3. Tabella Prodotti
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'T-shirt Tavolara Wear',
    slug TEXT UNIQUE NOT NULL DEFAULT 't-shirt-tavolara-wear',
    description TEXT,
    base_price NUMERIC(10,2) NOT NULL DEFAULT 30.00,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabella Varianti Prodotto (Colori: Blu, Bianca | Taglie: S, M, L, XL, XXL, 3XL)
CREATE TABLE IF NOT EXISTS public.product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
    color TEXT NOT NULL CHECK (color IN ('Blu', 'Bianca')),
    color_code TEXT NOT NULL CHECK (color_code IN ('navy', 'white')),
    size TEXT NOT NULL CHECK (size IN ('S', 'M', 'L', 'XL', 'XXL', '3XL')),
    sku TEXT UNIQUE,
    is_available BOOLEAN NOT NULL DEFAULT true,
    stock_qty INTEGER NOT NULL DEFAULT 50,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_product_color_size UNIQUE (product_id, color, size)
);
CREATE INDEX IF NOT EXISTS idx_product_variants_lookup ON public.product_variants(product_id, color, size);

-- 5. Tabella Ordini (Orders)
-- Include la distinzione chiara degli stati operativi e di pagamento
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    order_token TEXT UNIQUE NOT NULL,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    customer_first_name TEXT NOT NULL,
    customer_last_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    delivery_method TEXT NOT NULL CHECK (delivery_method IN ('locker', 'home', 'hand')),
    locker_name TEXT,
    delivery_address TEXT,
    delivery_zip TEXT,
    delivery_city TEXT,
    delivery_province TEXT,
    delivery_notes TEXT,
    hand_location TEXT,
    hand_preferences TEXT,
    shirt_price NUMERIC(10,2) NOT NULL,
    shipping_cost NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    discount_code TEXT,
    discount_amount NUMERIC(10,2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10,2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'bonifico',
    wire_causale TEXT NOT NULL,
    bank_holder TEXT,
    bank_iban TEXT,
    bank_name TEXT,
    status TEXT NOT NULL DEFAULT 'Ordine ricevuto' 
        CHECK (status IN ('Ordine ricevuto', 'Ordine confermato', 'Ordine da pagare', 'Ordine pagato', 'In preparazione', 'Spedito / Consegnato', 'Annullato')),
    payment_status TEXT NOT NULL DEFAULT 'da_pagare'
        CHECK (payment_status IN ('da_pagare', 'in_attesa', 'pagato', 'rimborsato')),
    privacy_accepted BOOLEAN NOT NULL DEFAULT true,
    privacy_timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    client_ip TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_status ON public.orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_payment_status ON public.orders(payment_status);
CREATE INDEX IF NOT EXISTS idx_orders_token ON public.orders(order_token);

-- 6. Tabella Righe Ordine (Order Items)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_id BIGINT REFERENCES public.products(id) ON DELETE SET NULL,
    variant_id BIGINT REFERENCES public.product_variants(id) ON DELETE SET NULL,
    product_name TEXT NOT NULL DEFAULT 'T-shirt Tavolara Wear',
    color TEXT NOT NULL CHECK (color IN ('Blu', 'Bianca')),
    color_code TEXT NOT NULL DEFAULT 'navy',
    size TEXT NOT NULL CHECK (size IN ('S', 'M', 'L', 'XL', 'XXL', '3XL')),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL,
    total_price NUMERIC(10,2) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON public.order_items(order_id);

-- 7. Tabella Transazioni / Incassi Effettivi (Attivo)
-- Le entrate consolidate riflettono gli incassi effettivi, non la stima degli ordini
CREATE TABLE IF NOT EXISTS public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL DEFAULT 'incasso' CHECK (type IN ('incasso', 'rimborso', 'rettifica')),
    order_id BIGINT REFERENCES public.orders(id) ON DELETE SET NULL,
    customer_id BIGINT REFERENCES public.customers(id) ON DELETE SET NULL,
    description TEXT NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    payment_method TEXT NOT NULL DEFAULT 'Bonifico bancario',
    status TEXT NOT NULL DEFAULT 'Incassata' CHECK (status IN ('Confermata', 'In attesa', 'Incassata')),
    reference TEXT,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_transactions_date ON public.transactions(date);
CREATE INDEX IF NOT EXISTS idx_transactions_status ON public.transactions(status);

-- 8. Tabella Categorie Spesa (Expense Categories)
CREATE TABLE IF NOT EXISTS public.expense_categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    code TEXT UNIQUE NOT NULL CHECK (code IN ('trasporto', 'imballaggio', 'prove', 'magliette')),
    description TEXT
);

-- 9. Tabella Spese / Uscite (Passivo — 4 Categorie)
CREATE TABLE IF NOT EXISTS public.expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.expense_categories(id) ON DELETE SET NULL,
    category_code TEXT NOT NULL CHECK (category_code IN ('trasporto', 'imballaggio', 'prove', 'magliette')),
    description TEXT NOT NULL,
    amount NUMERIC(10,2) NOT NULL CHECK (amount > 0),
    date DATE NOT NULL DEFAULT CURRENT_DATE,
    carrier TEXT,
    shipment_count INTEGER DEFAULT 1,
    shipment_type TEXT DEFAULT 'singola',
    material_type TEXT,
    quantity INTEGER DEFAULT 0,
    unit_cost NUMERIC(10,2) DEFAULT 0.00,
    proof_type TEXT,
    supplier TEXT,
    extra_production_costs NUMERIC(10,2) DEFAULT 0.00,
    notes TEXT,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_expenses_category ON public.expenses(category_code);
CREATE INDEX IF NOT EXISTS idx_expenses_date ON public.expenses(date);

-- 10. Tabella Configurazione Negozio
CREATE TABLE IF NOT EXISTS public.config (
    key TEXT PRIMARY KEY,
    value TEXT,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 11. Tabella Codici Sconto
CREATE TABLE IF NOT EXISTS public.discount_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    discount_type TEXT NOT NULL DEFAULT 'fixed',
    discount_value NUMERIC(10,2) NOT NULL DEFAULT 5.00,
    is_active BOOLEAN NOT NULL DEFAULT true,
    usage_count INTEGER NOT NULL DEFAULT 0,
    max_uses INTEGER,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

