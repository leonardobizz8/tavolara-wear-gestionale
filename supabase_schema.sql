-- ====================================================================
-- TAVOLARA WEAR — SCHEMA DATABASE SUPABASE CON RLS (ROW LEVEL SECURITY)
-- ====================================================================
-- Questo script SQL crea la struttura completa per il backend Supabase
-- con tabelle relazionali, Row-Level Security, funzioni di calcolo e trigger.

-- 1. Tabella Configurazione Globale
CREATE TABLE IF NOT EXISTS public.config (
    key TEXT PRIMARY KEY,
    value TEXT,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabella Varianti e Disponibilità Taglie/Colori
CREATE TABLE IF NOT EXISTS public.variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product TEXT NOT NULL DEFAULT 'T-shirt Tavolara Wear',
    color TEXT NOT NULL,         -- 'navy', 'white'
    color_name TEXT NOT NULL,    -- 'Blu navy', 'Bianca'
    size TEXT NOT NULL,          -- 'S', 'M', 'L', 'XL', 'XXL', 'XXXL'
    is_available BOOLEAN NOT NULL DEFAULT true,
    stock_qty INTEGER DEFAULT 50,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    CONSTRAINT unique_variant UNIQUE (color, size)
);

-- 3. Tabella Codici Sconto
CREATE TABLE IF NOT EXISTS public.discount_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code TEXT UNIQUE NOT NULL,
    discount_type TEXT NOT NULL DEFAULT 'fixed', -- 'fixed' o 'percentage'
    discount_value NUMERIC(10,2) NOT NULL DEFAULT 5.00,
    is_active BOOLEAN NOT NULL DEFAULT true,
    usage_count INTEGER NOT NULL DEFAULT 0,
    max_uses INTEGER,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabella Ordini
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    order_token TEXT UNIQUE NOT NULL,
    customer_first_name TEXT NOT NULL,
    customer_last_name TEXT NOT NULL,
    customer_email TEXT NOT NULL,
    customer_phone TEXT NOT NULL,
    delivery_method TEXT NOT NULL CHECK (delivery_method IN ('locker', 'home', 'hand')),
    locker_name TEXT,
    delivery_address TEXT,
    delivery_zip TEXT,
    delivery_city TEXT,
    delivery_province TEXT,
    delivery_notes TEXT,
    hand_location TEXT,
    hand_preferences TEXT,
    shirt_price NUMERIC(10,2),
    shipping_cost NUMERIC(10,2) DEFAULT 0.00,
    discount_code TEXT,
    discount_amount NUMERIC(10,2) DEFAULT 0.00,
    total_amount NUMERIC(10,2),
    payment_method TEXT NOT NULL DEFAULT 'bonifico',
    wire_causale TEXT NOT NULL,
    bank_holder TEXT,
    bank_iban TEXT,
    bank_name TEXT,
    status TEXT NOT NULL DEFAULT 'Nuovo ordine' CHECK (status IN ('Nuovo ordine', 'In attesa di pagamento', 'Pagamento verificato', 'In preparazione', 'Spedito / Consegnato', 'Annullato')),
    privacy_accepted BOOLEAN NOT NULL DEFAULT true,
    privacy_timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Tabella Righe Ordine (Articoli)
CREATE TABLE IF NOT EXISTS public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    product_name TEXT NOT NULL DEFAULT 'T-shirt Tavolara Wear',
    color TEXT NOT NULL,
    color_name TEXT NOT NULL,
    size TEXT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL,
    total_price NUMERIC(10,2) NOT NULL
);

-- ====================================================================
-- ROW LEVEL SECURITY (RLS) & SICUREZZA
-- ====================================================================

ALTER TABLE public.config ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.variants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.discount_codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

-- Config: anonimo può leggere solo chiavi pubbliche non sensibili
CREATE POLICY "Public read config" ON public.config
    FOR SELECT TO anon, authenticated
    USING (key NOT IN ('admin_password_hash'));

-- Config: solo admin può aggiornare
CREATE POLICY "Admin update config" ON public.config
    FOR ALL TO authenticated
    USING (auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role');

-- Varianti: tutti possono leggere la disponibilità
CREATE POLICY "Public read variants" ON public.variants
    FOR SELECT TO anon, authenticated
    USING (true);

-- Varianti: solo admin può modificare
CREATE POLICY "Admin modify variants" ON public.variants
    FOR ALL TO authenticated
    USING (auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role');

-- Codici sconto: anon può leggere per validazione
CREATE POLICY "Public read active discounts" ON public.discount_codes
    FOR SELECT TO anon, authenticated
    USING (is_active = true);

-- Ordini: anon può inserire nuovi ordini (checkout pubblico)
CREATE POLICY "Anon create order" ON public.orders
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

-- Righe ordine: anon può inserire per il proprio ordine
CREATE POLICY "Anon create order items" ON public.order_items
    FOR INSERT TO anon, authenticated
    WITH CHECK (true);

-- Ordini: i clienti NON possono leggere ordini altrui.
-- Solo tramite funzione sicura con order_token o ruolo admin/service_role
CREATE POLICY "Admin read all orders" ON public.orders
    FOR SELECT TO authenticated
    USING (auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role');

CREATE POLICY "Admin update orders" ON public.orders
    FOR UPDATE TO authenticated
    USING (auth.jwt() ->> 'role' = 'admin' OR auth.role() = 'service_role');

-- Funzione RPC protetta per recuperare l'ordine da parte del cliente tramite token segreto
CREATE OR REPLACE FUNCTION get_order_by_token(p_token TEXT)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    res json;
BEGIN
    SELECT json_build_object(
        'order', row_to_json(o),
        'items', (SELECT json_agg(row_to_json(i)) FROM order_items i WHERE i.order_id = o.id)
    )
    INTO res
    FROM orders o
    WHERE o.order_token = p_token;
    
    RETURN res;
END;
$$;

